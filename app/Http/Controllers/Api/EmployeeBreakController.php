    public function markBreak(Request $request)
    {
        $employeeId = $request->user()->employee->id;
        \Log::info('markBreak called', ['employeeId' => $employeeId, 'request' => $request->all()]);

        $request->validate([
            'break_type' => 'required|in:general,official',
            'reason' => 'required_if:break_type,official|nullable|string|max:255',
            'attendance_id' => 'required|exists:attendances,id',
        ]);

        // Fetch employee shift
        $employeeShift = EmployeeShift::where('emp_id', $employeeId)
            ->with('shift')
            ->latest('created_at')
            ->first();

        if (!$employeeShift || !$employeeShift->shift) {
            return response()->json(['success' => false, 'message' => 'Employee shift not found.'], 404);
        }

        // Validate that attendance is NOT checked out
        $attendance = Attendance::find($request->attendance_id);
        if ($attendance && $attendance->check_out) {
            \Log::warning('Blocked markBreak request for checked-out attendance', [
                'employeeId' => $employeeId,
                'attendance_id' => $attendance->id,
                'check_out' => $attendance->check_out
            ]);
            return response()->json([
                'success' => false,
                'message' => 'Cannot start break. You are already checked out.'
            ], 400);
        }


        // Get correct shift date
        $shiftDate = resolve_shift_date($employeeShift);
        \Log::info('Resolved shift date for markBreak', ['shiftDate' => $shiftDate]);

        $breakType = ucfirst(strtolower($request->break_type));

        // If user starts an official break while auto-inactivity break is active, convert it
        // instead of closing the auto break and creating a duplicate record.
        if ($breakType === 'Official') {
            $activeAuto = EmployeeBreak::where('emp_id', $employeeId)
                ->whereIn('status', ['On Break', 'On break', 'Ongoing'])
                ->where('type', 'General')
                ->where(function ($q) {
                    $q->where('reason', 'like', 'Auto break:%')
                        ->orWhere('reason', 'like', 'Auto-break%');
                })
                ->first();

            if ($activeAuto) {
                $activeAuto->type = 'Official';
                $activeAuto->reason = $request->reason;
                $activeAuto->save();

                $breakData = standardize_break_data_for_pusher($employeeId, $shiftDate, $activeAuto->id, $request->attendance_id);
                event(new \App\Events\BreakUpdated($employeeId, $breakData));
                clear_employee_app_data_cache($employeeId);

                return response()->json([
                    'success' => true,
                    'message' => 'Break started.',
                    'break' => $activeAuto,
                ]);
            }
        }

        // Close lingering active breaks — discard auto-generated ones instead of logging duplicates.
        EmployeeBreak::where('emp_id', $employeeId)
            ->whereIn('status', ['On Break', 'On break', 'Ongoing'])
            ->get()
            ->each(function ($break) {
                if ($break->isAutoGenerated()) {
                    $break->delete();
                } else {
                    $break->endBreak(['end_time' => now_with_timezone()]);
                }
            });

        // Create break
        $employeeBreak = new EmployeeBreak();
        $employeeBreak->emp_id = $employeeId;
        $employeeBreak->shift_date = $shiftDate; // ★ FIX
        $employeeBreak->attendance_id = $request->attendance_id;
        $employeeBreak->type = $breakType;
        $employeeBreak->reason = $request->reason;
        
        // Handle idle_duration if provided (in seconds)
        // This effectively "backdates" the break start to when the user actually went idle
        $startTime = now_with_timezone();
        if ($request->has('idle_duration')) {
            $idleSeconds = (int)$request->idle_duration;
            // Cap at 2 hours to prevent crazy values
            if ($idleSeconds > 0 && $idleSeconds < 7200) {
                 $startTime = $startTime->subSeconds($idleSeconds);
            }
        }
        
        $employeeBreak->start_time = $startTime;
        $employeeBreak->status = 'On Break';
        $employeeBreak->save();

        // Send update
        $breakData = standardize_break_data_for_pusher($employeeId, $shiftDate, $employeeBreak->id, $request->attendance_id);
        event(new \App\Events\BreakUpdated($employeeId, $breakData));

        clear_employee_app_data_cache($employeeId);

        return response()->json([
            'success' => true,
            'message' => 'Break started.',
            'break' => $employeeBreak
        ]);
    }
    public function endBreak(Request $request, $id = null)
    {
        $employeeId = $request->user()->employee->id;
        \Log::info('endBreak called', ['employeeId' => $employeeId, 'request' => $request->all(), 'id' => $id]);

        $request->validate([
            'break_type' => 'required|in:general,official',
            'reason' => 'required_if:break_type,official|nullable|string|max:255',
            'attendance_id' => 'required|exists:attendances,id',
        ]);

        // Fetch employee shift
        $employeeShift = EmployeeShift::where('emp_id', $employeeId)
            ->with('shift')
            ->latest('created_at')
            ->first();

        if (!$employeeShift || !$employeeShift->shift) {
            return response()->json(['success' => false, 'message' => 'Employee shift not found.'], 404);
        }

        // Correct shift date
        $shiftDate = resolve_shift_date($employeeShift);
        \Log::info('Resolved shift date for endBreak', ['shiftDate' => $shiftDate]);

        // Find active break
        if (!$id) {
            $break = EmployeeBreak::where('emp_id', $employeeId)
                ->whereIn('status', ['On Break', 'On break', 'Ongoing'])
                ->where('shift_date', $shiftDate)
                ->latest()
                ->first();

            if (!$break) {
                return response()->json(['success' => false, 'message' => 'No active break found.'], 404);
            }
        } else {
            $break = EmployeeBreak::where('emp_id', $employeeId)->findOrFail($id);
        }

        // === END BREAK USING ROBUST MODEL LOGIC ===
        $break->endBreak([
            'type' => ucfirst(strtolower($request->break_type)),
            'reason' => $request->reason,
            'attendance_id' => $request->attendance_id,
            'end_time' => now_with_timezone(),
        ]);

        EmployeeBreak::purgeSupersededAutoBreaks($employeeId, $shiftDate, $break->id);

        // Trigger Pusher update
        $breakData = standardize_break_data_for_pusher($employeeId, $shiftDate, null, $request->attendance_id);
        event(new \App\Events\BreakUpdated($employeeId, $breakData));

        clear_employee_app_data_cache($employeeId);

        return response()->json([
            'success' => true,
            'message' => 'Break ended.'
        ]);
    }
