    public function breakStatus($employeeId)
    {
        try {
            if ($employeeId != Auth::user()->employee->id) {
                return $this->sendError('Unauthorized access.', [], 403);
            }

            $assignedShift = $this->getTodayAssignedShift($employeeId);
            if (!$assignedShift) {
                return $this->sendResponse(['onBreak' => false], 'No assigned shift found.');
            }

            $shiftDate = Carbon::parse($assignedShift->shift_date)->toDateString();
            $attendance = Attendance::where('emp_id', $employeeId)
                ->whereDate('shift_date', $shiftDate)
                ->latest()
                ->first();

            if (!$attendance) {
                return $this->sendResponse(['onBreak' => false], 'No attendance found for assigned shift date.');
            }

            $ongoingBreak = EmployeeBreak::where('emp_id', $employeeId)
                ->where('status', 'On Break')
                ->first();

            return $this->sendResponse(
                ['onBreak' => $ongoingBreak ? true : false],
                'Break status fetched successfully.'
            );
        } catch (\Exception $e) {
            return $this->sendError('Failed to fetch break status.', ['error' => $e->getMessage()], 500);
        }
    }

