    public function getBreakStats()
    {
        try {
            $user = Auth::user();
            $employee = $user->employee;

            if (!$employee) {
                return response()->json(['error' => 'Employee not found.'], 404);
            }

            $assignedShift = $this->getTodayAssignedShift($employee->id);
            if (!$assignedShift) {
                return response()->json(['error' => 'Assigned shift not found.'], 404);
            }

            $shiftDate = Carbon::parse($assignedShift->shift_date)->toDateString();
            $allowedBreakMinutes = get_effective_break_minutes((int) $employee->id, $shiftDate);

            $breaks = EmployeeBreak::where('emp_id', $employee->id)
                ->whereIn('type', ['General', 'Official']) // Include both types
                ->where('status', 'Completed')
                ->whereDate('end_time', $shiftDate)
                ->get();

            $totalSpentMinutes = 0;
            foreach ($breaks as $break) {
                if ($break->start_time && $break->end_time) {
                    try {
                        $start = Carbon::parse($break->start_time);
                        $end = Carbon::parse($break->end_time);
                        if ($end->greaterThan($start)) {
                            $totalSpentMinutes += $start->diffInMinutes($end);
                        }
                    } catch (\Exception $e) {
                        continue;
                    }
                }
            }

            $totalSpentMinutes = round($totalSpentMinutes);
            $remaining = max(round($allowedBreakMinutes - $totalSpentMinutes), 0);
            $exceeded = max(round($totalSpentMinutes - $allowedBreakMinutes), 0);

            $formatMinutes = function ($minutes) {
                $hours = floor($minutes / 60);
                $mins = $minutes % 60;
                $parts = [];
                if ($hours > 0)
                    $parts[] = "$hours hour" . ($hours > 1 ? 's' : '');
                if ($mins > 0)
                    $parts[] = "$mins minute" . ($mins > 1 ? 's' : '');
                return count($parts) > 0 ? implode(' ', $parts) : '0 minutes';
            };

            $employeeService = app(\App\Services\EmployeeService::class);
            $breakStats = calculate_break_stats($employee, $assignedShift, $shiftDate);

            return response()->json($breakStats);
        } catch (\Exception $e) {
            \Log::error('getBreakStats: Failed to fetch break stats.', [
                'employeeId' => $employee->id ?? null,
                'error' => $e->getMessage(),
            ]);
            return response()->json(['error' => 'Failed to fetch break stats.'], 500);
        }
    }

